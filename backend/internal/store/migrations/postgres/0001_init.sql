CREATE TABLE blobs (
    sha256      TEXT PRIMARY KEY,
    encoding    TEXT NOT NULL,
    media_type  TEXT NOT NULL,
    size        BIGINT NOT NULL,
    content     BYTEA NOT NULL
);

CREATE TABLE apis (
    id                  TEXT PRIMARY KEY,
    name                TEXT NOT NULL,
    owner               TEXT,
    source_url          TEXT NOT NULL,
    source_type         TEXT NOT NULL,
    resolved_spec_url   TEXT,
    config_json         TEXT NOT NULL,
    enabled             BOOLEAN NOT NULL DEFAULT TRUE,
    status              TEXT NOT NULL DEFAULT 'pending',
    last_error          TEXT,
    consecutive_errors  INTEGER NOT NULL DEFAULT 0,
    etag                TEXT,
    last_modified       TEXT,
    current_snapshot_id BIGINT,
    last_checked_at     TIMESTAMPTZ,
    next_check_at       TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE snapshots (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_id            TEXT NOT NULL REFERENCES apis(id),
    fetched_at        TIMESTAMPTZ NOT NULL,
    raw_sha256        TEXT NOT NULL REFERENCES blobs(sha256),
    normalized_sha256 TEXT NOT NULL REFERENCES blobs(sha256),
    spec_format       TEXT NOT NULL,
    info_version      TEXT,
    title             TEXT,
    operation_count   INTEGER,
    UNIQUE (api_id, normalized_sha256)
);
CREATE INDEX idx_snapshots_api ON snapshots(api_id, fetched_at DESC);
ALTER TABLE apis ADD CONSTRAINT fk_apis_current_snapshot FOREIGN KEY (current_snapshot_id) REFERENCES snapshots(id);

CREATE TABLE checks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_id       TEXT NOT NULL REFERENCES apis(id),
    started_at   TIMESTAMPTZ NOT NULL,
    duration_ms  BIGINT,
    trigger      TEXT NOT NULL,
    status       TEXT NOT NULL,
    error_kind   TEXT,
    http_status  INTEGER,
    error        TEXT,
    snapshot_id  BIGINT REFERENCES snapshots(id)
);
CREATE INDEX idx_checks_api ON checks(api_id, started_at DESC);

CREATE TABLE changes (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_id            TEXT NOT NULL REFERENCES apis(id),
    from_snapshot_id  BIGINT REFERENCES snapshots(id),
    to_snapshot_id    BIGINT NOT NULL REFERENCES snapshots(id),
    detected_at       TIMESTAMPTZ NOT NULL,
    version_from      TEXT,
    version_to        TEXT,
    error_count       INTEGER NOT NULL DEFAULT 0,
    warn_count        INTEGER NOT NULL DEFAULT 0,
    info_count        INTEGER NOT NULL DEFAULT 0,
    in_scope_count    INTEGER NOT NULL DEFAULT 0,
    semantic          BOOLEAN NOT NULL DEFAULT TRUE,
    acknowledged_at   TIMESTAMPTZ,
    acknowledged_by   TEXT
);
CREATE INDEX idx_changes_api ON changes(api_id, detected_at DESC);

CREATE TABLE change_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_id  BIGINT NOT NULL REFERENCES changes(id) ON DELETE CASCADE,
    rule_id    TEXT NOT NULL,
    level      TEXT NOT NULL,
    method     TEXT,
    path       TEXT,
    in_scope   BOOLEAN NOT NULL DEFAULT TRUE,
    text       TEXT NOT NULL
);
CREATE INDEX idx_change_items_change ON change_items(change_id);

CREATE TABLE notifications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_id    BIGINT REFERENCES changes(id),
    api_id       TEXT NOT NULL REFERENCES apis(id),
    notifier     TEXT NOT NULL,
    kind         TEXT NOT NULL,
    status       TEXT NOT NULL DEFAULT 'pending',
    attempts     INTEGER NOT NULL DEFAULT 0,
    last_error   TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at      TIMESTAMPTZ,
    UNIQUE (change_id, notifier)
);
